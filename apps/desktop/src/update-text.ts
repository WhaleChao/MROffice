let pageLocale: UpdateLocale | null = null;

/**
 * The closest of the tables to a BCP 47 tag ("zh-Hant-TW", "pt-PT", "nb"...),
 * or null: the web app's own rules (./classic/web-locales.ts pickLocale, as
 * the site picks a page's language), over the languages these dialogs are
 * written in.
 */
export function matchUpdateLocale(tag: string | null | undefined): UpdateLocale | null {
  return pickLocale(tag, UPDATE_LOCALES);
}

/** The language the app's pages show (Settings tells it). */
export function setUpdateLocale(tag: string | null | undefined): void {
  const matched = matchUpdateLocale(tag);
  if (matched) pageLocale = matched;
}

/** The dialogs' language: the page's, else the app's (../app-locale.ts), else the computer's, else English. */
export function updateLocale(): UpdateLocale {
  if (pageLocale) return pageLocale;
  for (const tag of [appLocale(), ...systemLanguageTags()]) {
    const matched = matchUpdateLocale(tag);
    if (matched) return matched;
  }
  return "en";
}

/** One string, its {placeholders} filled. */
export function ut(key: Key, values: Record<string, string | number> = {}, locale: UpdateLocale = updateLocale()): string {
  const template = TEXT[locale]?.[key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}

