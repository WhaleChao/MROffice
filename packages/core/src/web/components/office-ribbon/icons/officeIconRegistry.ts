export type OfficeSemanticIconId = (typeof OFFICE_SEMANTIC_ICON_IDS)[number];

export interface OfficeIconRegistration {
  semanticId: OfficeSemanticIconId;
  literalMetaphor: string;
  mirrorInRtl: boolean;
  semanticAccentCount: 0 | 1 | 2;
}

function registerOfficeIcon(
  semanticId: OfficeSemanticIconId,
  literalMetaphor: string,
  mirrorInRtl: boolean,
  semanticAccentCount: 0 | 1 | 2,
): OfficeIconRegistration {
  return {
    semanticId,
    literalMetaphor,
    mirrorInRtl,
    semanticAccentCount,
  };
}

