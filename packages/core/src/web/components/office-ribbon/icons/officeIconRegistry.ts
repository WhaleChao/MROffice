export function isOfficeSemanticIconId(
  value: string,
): value is OfficeSemanticIconId {
  return Object.prototype.hasOwnProperty.call(OFFICE_ICON_REGISTRY, value);
}

export type OfficePageOrientation = "portrait" | "landscape";

/**
 * The one Portrait/Landscape pair. Every editor's orientation choice (Docs and
 * Sheets Orientation menus, the slide size dialog, PDF page dialogs) resolves
 * its value here so the two faces never drift apart between editors.
 */
export const OFFICE_PAGE_ORIENTATION_ICON_IDS = Object.freeze({
  portrait: "page.orientation.portrait",
  landscape: "page.orientation.landscape",
} as const satisfies Record<OfficePageOrientation, OfficeSemanticIconId>);
