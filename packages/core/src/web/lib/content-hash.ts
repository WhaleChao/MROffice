/** cyrb53: a fast 53-bit string hash, as base-36 text. Two texts that hash
 * alike are taken as the same content by a cache keyed on it; a caller whose
 * cache must never confuse two texts compares them again on a hit. */
export function hash53(text: string): string {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let index = 0; index < text.length; index += 1) {
    const code = text.charCodeAt(index);
    h1 = Math.imul(h1 ^ code, 2654435761);
    h2 = Math.imul(h2 ^ code, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36);
}

/** The hash and the length of `text`: what a cache keeps instead of the
 * text itself when the text is large. */
export function contentKey(text: string): string {
  return `${text.length.toString(36)}.${hash53(text)}`;
}
