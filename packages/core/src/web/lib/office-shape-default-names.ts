export function officeDefaultShapeNameAfterChange(
  name: unknown,
  shapeNumber: number,
  fromPreset: string | null | undefined,
  toPreset: string | null | undefined,
): string | null {
  if (typeof name !== "string" || !Number.isInteger(shapeNumber) || shapeNumber < 1) return null;
  const has = (preset: string | null | undefined): preset is string =>
    typeof preset === "string" && Object.prototype.hasOwnProperty.call(OFFICE_PRESET_DEFAULT_NAME_BASES, preset);
  if (!has(fromPreset) || !has(toPreset) || fromPreset === toPreset) return null;
  const number = shapeNumber - 1;
  if (name !== `${OFFICE_PRESET_DEFAULT_NAME_BASES[fromPreset]} ${number}`) return null;
  return `${OFFICE_PRESET_DEFAULT_NAME_BASES[toPreset]} ${number}`;
}
