// ---------------------------------------------------------------------------
// Spreadsheet function signatures — the argument list of every function the
// formula engine evaluates, spelled the way Excel's own tooltip spells it.
//
// PURE data, no imports. Three consumers read it and must agree:
//
//   - formula-intellisense: the argument hint shown while typing a call;
//   - function-arguments:   one labelled input per argument in the fx wizard;
//   - formula-engine:       the argument COUNT a call must have. Excel refuses a
//     formula with too few or too many arguments before it ever evaluates it,
//     so a call outside the range this table implies is an error rather than a
//     silently-defaulted answer.
//
// Label conventions: "[name]" is an optional argument, and a final "…" means the
// argument(s) before it repeat (SUM(number1, [number2], …)). The minimum
// argument count is the number of unbracketed labels; a variadic function takes
// up to 255 arguments, which is Excel's limit for any call.
// ---------------------------------------------------------------------------

export interface FunctionSignatureSpec {
  /** Ordered argument labels, e.g. ["number1", "[number2]", "…"]. */
  readonly args: readonly string[];
  /** Whether the argument(s) before the trailing "…" repeat. */
  readonly variadic: boolean;
}

/** Excel's hard limit on the number of arguments in one function call. */
export const MAX_FUNCTION_ARGS = 255;

const ELLIPSIS = "…";

/** Build a spec from a compact ", "-separated label list. */
function sig(spec: string): FunctionSignatureSpec {
  const args = spec === "" ? [] : spec.split(", ");
  return { args, variadic: args[args.length - 1] === ELLIPSIS };
}

