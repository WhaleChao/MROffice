/** The spec for a (case-insensitive) function name, or undefined. */
export function functionSignatureSpec(name: string): FunctionSignatureSpec | undefined {
  const upper = name.toUpperCase();
  return Object.prototype.hasOwnProperty.call(FUNCTION_SIGNATURES, upper)
    ? FUNCTION_SIGNATURES[upper]
    : undefined;
}

/**
 * How many arguments a call may carry: the unbracketed labels are required, and
 * a variadic function accepts up to Excel's 255. An empty slot (`f(1,,3)`)
 * counts as an argument, exactly as it does in Excel.
 */
export function functionArity(name: string): { min: number; max: number } | null {
  const spec = functionSignatureSpec(name);
  if (!spec) return null;
  const named = spec.args.filter((label) => label !== ELLIPSIS);
  const min = named.filter((label) => !label.startsWith("[")).length;
  const max = spec.variadic ? MAX_FUNCTION_ARGS : named.length;
  return { min, max };
}

