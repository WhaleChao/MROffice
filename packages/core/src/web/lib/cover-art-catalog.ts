import type {
  CoverArt,
  CoverArtGroup,
  CoverArtLayer,
  CoverArtParticles,
  CoverArtPlaces,
} from "./cover-art";

// The painted covers (lib/cover-art.ts), in picker order within each group.
// "ink" is the title's: light over a dark painting, dark over a light one;
// a moving cover lists what moves and, for a light that breathes or
// flickers, where that light is (% of the cover). Where a painting's sky,
// water, plants or mist sit away from the recipes' defaults, or its light
// reaches further or less far, its places say so (read off the painting,
// so each moving part keeps to its own region and a shifted copy never
// crosses an edge it would double).

const still = (slug: string, group: CoverArtGroup, ink: CoverArt["ink"]): CoverArt => ({
  id: `art-${slug}`,
  group,
  ink,
});

const moving = (
  slug: string,
  group: CoverArtGroup,
  ink: CoverArt["ink"],
  layers: string,
  particles?: CoverArtParticles,
  light?: readonly [number, number],
  places?: CoverArtPlaces,
): CoverArt => ({
  id: `art-${slug}`,
  group,
  ink,
  layers: layers.split(" ").filter(Boolean) as CoverArtLayer[],
  ...(particles ? { particles } : {}),
  ...(light ? { light } : {}),
  ...(places ? { places } : {}),
});

